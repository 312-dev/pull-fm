const MBID_RE =
  /^[0-9a-fA-F]{8}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{12}$/;

const LISTENBRAINZ_ATTRIBUTION: Attribution = {
  source: "listenbrainz",
  text: "Recommendations by ListenBrainz",
  url: "https://listenbrainz.org",
};

const NO_CONNECTION = new Error("no ListenBrainz connection for this subject");

/**
 * Signals "do not spend an upstream call on this identifier".
 *
 * A thrown sentinel rather than a return value, because the decision has to
 * happen inside `CachedUpstream.fetch`'s `load` closure - the only place that
 * runs on a miss and not on a hit - and `load` must produce a payload or fail.
 * Failing is the correct shape anyway: `#fill` then writes nothing, so a
 * declined lookup leaves no trace to invalidate later.
 */
const NOT_WORTH_ASKING = new Error(
  "artist mbid is not known to any local record; declining the upstream call",
);

function attributionOf(a: Attribution): Attribution {
  return { source: a.source, text: a.text };
}

function lastfmAttribution(url: string | undefined): Attribution {
  return {
    source: "lastfm",
    text: LASTFM_ATTRIBUTION,
    ...(url === undefined ? {} : { url }),
  };
}

function emptyEnvelope(unavailable: readonly string[]): SectionsEnvelope {
  return {
    sections: [],
    cursor: null,
    degraded: unavailable.length > 0,
    unavailableProviders: [...unavailable],
    attribution: [],
  };
}

function displayNameOf(hit: CrosswalkHit): string {
  return hit.normalizedKey;
}

function asArray(payload: unknown): unknown[] {
  return Array.isArray(payload) ? payload : [];
}

function stringField(row: unknown, key: string): string | null {
  if (row === null || typeof row !== "object") return null;
  const value = (row as Record<string, unknown>)[key];
  return typeof value === "string" && value.length > 0 ? value : null;
}

function numberField(row: unknown, key: string): number | null {
  if (row === null || typeof row !== "object") return null;
  const value = (row as Record<string, unknown>)[key];
  return typeof value === "number" && Number.isFinite(value) ? value : null;
}

function parseCachedArtist(payload: unknown): MusicBrainzArtist | null {
  const mbid = stringField(payload, "mbid");
  const name = stringField(payload, "name");
  if (mbid === null || name === null) return null;
  // Nothing reads `tags` off a cached row even if an older build wrote one:
  // supplementary MusicBrainz data is CC BY-NC-SA 3.0 and this response is
  // CC0-only. A row written before the client stopped requesting them is
  // therefore forward-compatible rather than a licence problem.
  return {
    mbid,
    name,
    sortName: stringField(payload, "sortName") ?? undefined,
    country: stringField(payload, "country") ?? undefined,
    beganYear: numberField(payload, "beganYear") ?? undefined,
  };
}

function parseCachedRecording(payload: unknown): MusicBrainzRecording | null {
  const mbid = stringField(payload, "mbid");
  const title = stringField(payload, "title");
  if (mbid === null || title === null) return null;
  return {
    mbid,
    title,
    lengthMs: numberField(payload, "lengthMs") ?? undefined,
    artistMbid: stringField(payload, "artistMbid") ?? undefined,
    artistName: stringField(payload, "artistName") ?? "Unknown Artist",
  };
}

function parseCachedRelease(payload: unknown): MusicBrainzRelease | null {
  const mbid = stringField(payload, "mbid");
  const title = stringField(payload, "title");
  if (mbid === null || title === null) return null;
  return {
    mbid,
    title,
    date: stringField(payload, "date") ?? undefined,
    country: stringField(payload, "country") ?? undefined,
    trackCount: numberField(payload, "trackCount") ?? undefined,
    artistMbid: stringField(payload, "artistMbid") ?? undefined,
    artistName: stringField(payload, "artistName") ?? "Unknown Artist",
  };
}


/**
 * The product surface, implemented.
 *
 * `packages/discovery` owns the ranking and knows nothing about HTTP or about
 * caching. This file is the adapter between the two: it implements
 * `DiscoveryPorts` over `CachedUpstream`, so the blend cannot reach a provider
 * even by mistake, and it turns the resulting `SectionsEnvelope` into the wire
 * shape the OpenAPI document already published.
 *
 * WHAT IS SYNCHRONOUS AND WHAT IS NOT
 * -----------------------------------
 * See services/upstream.ts for the per-provider argument. The consequences
 * visible in this file:
 *
 *   - Every ListenBrainz and Last.fm read is `cache.fetch`, a read-through
 *     with a TTL. Their budgets are per-token and per-app-key respectively,
 *     which are budgets a single request may legitimately spend.
 *   - Every MusicBrainz read is `cache.peek`, which never calls out. A miss is
 *     a missing name, not a lookup. That is what `hydrateRecordings` returning
 *     a partial map is for, and why `made_for_you` can be empty on a cold cache
 *     while every other shelf still renders.
 *   - Preview reads come from `track_previews` (iTunes, persistable) and, only
 *     when that misses, from a live Deezer resolve whose result is deliberately
 *     thrown away after it is returned once.
 *
 * DEGRADATION IS THE CONTRACT, NOT AN ERROR PATH
 * ----------------------------------------------
 * A dead provider removes one shelf and sets `degraded`. `buildFeed` already
 * does this and the adapter must not undo it, so every port method converts an
 * upstream degradation into an empty result or a throw that `buildFeed` catches
 * per-section, never into a rejection that escapes to the route.
 *
 * CREDENTIALS
 * -----------
 * `#listenBrainzPort` receives the plaintext token as a closure argument and
 * passes it straight to the client. It is never assigned to the request, the
 * reply, a cache key, an error, or a log line. `.semgrep/pullfm.yml` enforces
 * the first and last of those mechanically.
 */


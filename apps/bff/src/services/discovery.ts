// ---------------------------------------------------------------------------
// Cache keys and TTLs.
//
// TTLs are chosen against how fast the answer changes, EXCEPT where a licence
// says otherwise. Last.fm's is long because their 100 MB cap (ToS 4.3.4) is
// relieved by fewer, longer-lived rows, not by more of them.
// ---------------------------------------------------------------------------
const TTL = {
  /** Regenerated by ListenBrainz on a multi-day cadence. */
  recommendations: 6 * 60 * 60,
  /** Listening statistics move slowly and a stale hour is invisible. */
  topArtists: 6 * 60 * 60,
  /** Artist radio is derived from a similarity model, not from activity. */
  artistRadio: 24 * 60 * 60,
  /** Weekly Jams / Weekly Discovery are rewritten weekly. */
  playlists: 60 * 60,
  /** labs.api has no SLA; a long TTL is what makes it survivable. */
  labsSimilar: 7 * 24 * 60 * 60,
  /** Last.fm: long by licence, not by volatility. */
  lastfm: 7 * 24 * 60 * 60,
  /**
   * MusicBrainz core data. CC0, with no cache cap and no storage limit, so this
   * is bounded only by how often a title is corrected or an MBID merged.
   */
  musicbrainz: 30 * 24 * 60 * 60,
} as const;

/**
 * Sections per feed page.
 *
 * Small enough that a first render is cheap on a phone, and large enough that
 * the common case is a single page. The cursor is what makes this changeable
 * without a client release.
 */
const SECTIONS_PER_PAGE = 4;

/** Trigram floor for `GET /v1/search`. Below this the results are noise. */
const SEARCH_MIN_SIMILARITY = 0.25;

